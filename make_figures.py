"""Regenerate current manuscript F06-F10 using only packaged inputs.

The exact submitted ten figure assets are under docs/manuscript/figures.
F01-F05 are supplied as assets, not regenerated by this entry point.
"""
from pathlib import Path
from types import SimpleNamespace
import argparse
import importlib
import json
import os
import shutil
import subprocess
import sys

ROOT=Path(__file__).resolve().parent
SCRIPTS=ROOT/'code/publication_figures'
DATA=ROOT/'data/publication_figures'
sys.dont_write_bytecode=True

def run(script,*args):
    env=dict(os.environ,PYTHONDONTWRITEBYTECODE='1')
    subprocess.run([sys.executable,str(SCRIPTS/script),*map(str,args)],check=True,env=env)

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--figures',type=int,nargs='+',choices=[6,7,8,9,10],default=[6,7,8,9,10])
    p.add_argument('--output',type=Path,default=ROOT/'work/figures')
    p.add_argument('--dpi',type=int,default=600)
    a=p.parse_args();out=a.output.resolve();out.mkdir(parents=True,exist_ok=True)
    if ROOT==out or ROOT in out.parents and not out.is_relative_to(ROOT/'work'):
        p.error('Use an external output directory or a directory under work/.')
    sys.path.insert(0,str(SCRIPTS))
    manifest=[]
    for number in dict.fromkeys(a.figures):
        if number==6:
            source=ROOT/'supplementary_data/D08_tensor_predictions.csv'
            run('plot_alpha_component_parity.py','--inplane-predictions',source,
                '--zz-predictions',source,'--output',out/'F06.png','--dpi',a.dpi)
        elif number==7:
            import matplotlib.pyplot as plt
            import numpy as np
            import pandas as pd
            module=importlib.import_module('plot_tensor_error_comparison')
            data=pd.read_csv(DATA/'F07_unified_paired_errors.csv').set_index('id')
            config=SimpleNamespace(layout='vertical',width_mm=85.,height_mm=114.,
                font_size=9.,error_scale='log',delta_linthresh=.25,dpi=a.dpi)
            fig,groups,counts=module.make_figure(data,config,np.array([1.,5.,10.]))
            for ext in ['png','pdf']:fig.savefig(out/f'F07.{ext}',dpi=a.dpi,facecolor='white')
            plt.close(fig)
        elif number==8:
            source=ROOT/'supplementary_data/D14_classifier_oof.csv'
            target=out/'F08_details'
            run('plot_classifier_roc_pr.py','--cat-oof',source,'--alignn-oof',source,
                '--fusion-oof',source,'--cat-prob-column','p_catboost',
                '--alignn-prob-column','p_alignn','--fusion-prob-column','p_fused',
                '--layout','vertical','--width-mm',85,'--output-dir',target,'--dpi',a.dpi)
            for ext in ['png','pdf']:
                files=list(target.glob('*.'+ext))
                if len(files)!=1:raise RuntimeError(f'Expected one F08 {ext}: {files}')
                shutil.copy2(files[0],out/f'F08.{ext}')
        elif number==9:
            import pandas as pd
            module=importlib.import_module('plot_candidate_material_map')
            points=pd.read_csv(DATA/'F09_colorbar_context.csv')
            candidates=pd.read_csv(ROOT/'supplementary_data/D04_tensor_candidates.csv')
            module.draw(points,candidates,SimpleNamespace(width_mm=177.,height_mm=100.,
                output=out/'F09.png',dpi=a.dpi))
        elif number==10:
            run('plot_bands_with_offsets.py','--materials-root',DATA/'materials',
                '--output',out/'F10.png')
        manifest.append({'figure':number,'pdf':f'F{number:02d}.pdf','png':f'F{number:02d}.png'})
    (out/'generated_figures.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    print('Current manuscript layouts generated:',out)

if __name__=='__main__':main()
